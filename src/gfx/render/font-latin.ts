/** Order of glyphs on the generated sheet. */
export const GLYPH_ORDER: readonly string[] = Object.keys(GLYPHS);

/** Lower case maps to capitals, except the lone 'x' used as a multiplication sign. */
export function glyphKey(ch: string): string {
  if (ch in GLYPHS && ch !== 'x') return ch;
  const upper = ch.toUpperCase();
  return upper in GLYPHS ? upper : '?';
}
